"use strict";

/* Software Supply Chain Guardian dashboard (vanilla JS, no build step).
 * All data comes from the read-only API in dashboard/app.py. Values from the
 * scanned repo (component names, paths, ...) are untrusted, so every node is
 * built with textContent - never innerHTML. */

const POLL_MS = 5000;
const STAGES = [
  { id: "discover",  name: "Discover",  agent: "discovery" },
  { id: "detect",    name: "Detect",    agent: "detection" },
  { id: "analyze",   name: "Analyze",   agent: "analysis" },
  { id: "remediate", name: "Remediate", agent: "remediation" },
  { id: "validate",  name: "Validate",  agent: "validation" },
];
const STATE_LABEL = { pending: "Pending", running: "Running", done: "Done", failed: "Failed" };
const TILES = [
  ["components", "Total components"],
  ["direct", "Direct"],
  ["transitive", "Transitive"],
  ["ecosystems", "Ecosystems"],
  ["manifests", "Manifests found"],
  ["lockfiles_generated", "Lockfiles generated by us"],
];
const COLUMNS = [
  { key: "name", label: "Name" },
  { key: "version", label: "Version" },
  { key: "ecosystem", label: "Ecosystem" },
  { key: "scope", label: "Scope" },
  { key: "relationship", label: "Direct / transitive" },
  { key: "license", label: "License" },
  { key: "purl", label: "purl" },
];
const PAGE_SIZES = [25, 50, 100, 250];

const state = {
  runs: [],
  app: null,
  run: null,
  agents: {},
  stage: "discover",
  panelKey: null,
  discovery: { key: null, meta: null, components: [], error: null },
  table: { q: "", relationship: "", ecosystem: "", scope: "", sortKey: "name", sortDir: 1, page: 1, size: 50 },
};

/* ---------- helpers ---------- */

function h(tag, attrs, ...children) {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs || {})) {
    if (v == null || v === false) continue;
    if (k === "class") el.className = v;
    else if (k.startsWith("on")) el.addEventListener(k.slice(2), v);
    else el.setAttribute(k, v === true ? "" : v);
  }
  for (const c of children.flat(Infinity)) {
    if (c == null || c === false) continue;
    el.append(c instanceof Node ? c : document.createTextNode(String(c)));
  }
  return el;
}

const $ = (id) => document.getElementById(id);
const enc = encodeURIComponent;
const fmtNum = (n) => (typeof n === "number" ? n.toLocaleString() : n ?? "–");

async function getJSON(url) {
  const res = await fetch(url, { cache: "no-store" });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} - ${url}`);
  return res.json();
}

function relTime(iso) {
  if (!iso) return "–";
  const t = new Date(iso);
  if (Number.isNaN(t.getTime())) return iso;
  const s = Math.round((t - Date.now()) / 1000);
  const rtf = new Intl.RelativeTimeFormat(undefined, { numeric: "auto" });
  const abs = Math.abs(s);
  if (abs < 60) return rtf.format(s, "second");
  if (abs < 3600) return rtf.format(Math.round(s / 60), "minute");
  if (abs < 86400) return rtf.format(Math.round(s / 3600), "hour");
  return rtf.format(Math.round(s / 86400), "day");
}

const fmtDate = (iso) => (iso ? new Date(iso).toLocaleString() : "");

function badge(st) {
  const s = STATE_LABEL[st] ? st : "pending";
  return h("span", { class: `badge ${s}` }, STATE_LABEL[s]);
}

function statusForStage(stageId) {
  return Object.values(state.agents).find((a) => a.stage === stageId) || null;
}

function artifactUrl(agent, name, download) {
  return `/api/runs/${enc(state.app)}/${enc(agent)}/artifact/${enc(name)}${download ? "?download=true" : ""}`;
}

function readHash() {
  const p = new URLSearchParams(location.hash.slice(1));
  return { app: p.get("app"), stage: p.get("stage") };
}

function writeHash() {
  const p = new URLSearchParams();
  if (state.app) p.set("app", state.app);
  p.set("stage", state.stage);
  history.replaceState(null, "", `#${p}`);
}

/* ---------- top bar ---------- */

function renderAppSelect() {
  const sel = $("app-select");
  const names = state.runs.map((r) => r.app_name);
  const current = [...sel.options].map((o) => o.value);
  if (names.join("|") !== current.join("|")) {
    sel.replaceChildren(...(names.length ? names.map((n) => h("option", { value: n }, n))
                                         : [h("option", { value: "" }, "No runs yet")]));
  }
  sel.disabled = !names.length;
  sel.value = state.app || "";
}

function renderRunMeta() {
  const run = state.run || {};
  const url = run.repo_url;
  const sha = run.commit_sha;
  const item = (label, value, title) => h("div", null, h("dt", null, label), h("dd", { title }, value));
  $("run-meta").replaceChildren(
    item("Repository", url ? h("a", { href: url, target: "_blank", rel: "noopener noreferrer" },
                               url.replace(/^https?:\/\//, "")) : "–", url),
    item("Commit", sha ? h("span", { class: "mono" }, sha.slice(0, 7)) : "–", sha),
    item("Last run", relTime(run.updated_at), fmtDate(run.updated_at)),
  );
}

/* ---------- pipeline ---------- */

function renderPipeline() {
  $("pipeline").replaceChildren(...STAGES.map((stage, i) => {
    const st = statusForStage(stage.id);
    const agentName = st ? st.agent : stage.agent;
    return h("button", {
      class: "stage", type: "button", "aria-current": state.stage === stage.id ? "true" : "false",
      onclick: () => selectStage(stage.id),
    },
      h("span", { class: "stage-step" }, `Stage ${i + 1}`),
      h("span", { class: "stage-name" }, stage.name),
      h("span", { class: "stage-agent" }, `${agentName} agent`),
      badge(st ? st.state : "pending"),
    );
  }));
}

function selectStage(id) {
  if (state.stage === id) return;
  state.stage = id;
  state.panelKey = null;
  writeHash();
  renderPipeline();
  renderPanel();
}

/* ---------- panels ---------- */

function stageKey(st) {
  return st ? `${st.state}|${st.started_at}|${st.finished_at}` : "none";
}

function renderPanel(force) {
  const stage = STAGES.find((s) => s.id === state.stage);
  const st = statusForStage(stage.id);
  const key = `${state.app}|${stage.id}|${stageKey(st)}|${state.discovery.key}`;
  if (!force && key === state.panelKey) return;
  state.panelKey = key;

  const panel = $("panel");
  if (!state.app) {
    panel.replaceChildren(h("div", { class: "empty" },
      h("h3", null, "No runs found in outputs/"),
      h("p", null, "Run the Discovery Agent first: ",
        h("code", null, "python -m agents.discovery.cli --repo <url>"))));
    return;
  }

  const head = h("div", { class: "panel-head" },
    h("h2", null, stage.name),
    h("span", { class: "sub" }, `${st ? st.agent : stage.agent} agent`),
    badge(st ? st.state : "pending"),
    st && st.finished_at ? h("span", { class: "sub", title: fmtDate(st.finished_at) },
                             `finished ${relTime(st.finished_at)}`) : null,
  );

  let body;
  if (!st) body = emptyState("No output yet", `The ${stage.agent} agent has not written any results for this app.`);
  else if (st.state === "failed") body = failedState(st);
  else if (st.state !== "done") body = emptyState("Running…", `Started ${relTime(st.started_at)}. This view updates automatically.`);
  else if (stage.id === "discover") body = discoveryPanel(st);
  else body = genericPanel(st);

  panel.replaceChildren(head, body);
  if (stage.id === "discover" && st && st.state === "done") renderTable();
}

function emptyState(title, text) {
  return h("div", { class: "empty" }, h("h3", null, title), h("p", null, text));
}

function failedState(st) {
  return h("div", { class: "stack" },
    h("div", { class: "error-box" }, h("strong", null, "The agent failed"), h("pre", null, st.error || "Unknown error")),
    artifactsCard(st));
}

function genericPanel(st) {
  return h("div", { class: "stack" }, tilesRow(st.summary || {}, null), artifactsCard(st));
}

function tilesRow(summary, defs) {
  const entries = defs || Object.keys(summary).map((k) => [k, k.replace(/_/g, " ")]);
  return h("div", { class: "tiles" }, entries.map(([k, label]) =>
    h("div", { class: "tile" }, h("div", { class: "tile-value" }, fmtNum(summary[k])), h("div", { class: "tile-label" }, label))));
}

function artifactsCard(st) {
  const items = st.artifacts || [];
  return h("div", { class: "card" },
    h("h3", null, "Artifacts"),
    items.length
      ? h("ul", { class: "artifacts" }, items.map((a) => h("li", null,
          h("div", null, h("div", { class: "a-name" }, a.name), h("div", { class: "a-meta" }, `${a.type} · ${a.path}`)),
          h("a", { class: "btn", href: artifactUrl(st.agent, a.name, true), download: a.name }, "Download"))))
      : h("p", { class: "muted" }, "No artifacts listed."));
}

/* ---------- discovery ---------- */

async function loadDiscovery(st) {
  const key = stageKey(st);
  if (state.discovery.key === key) return;
  if (!st || st.state !== "done") {
    state.discovery = { key, meta: null, components: [], error: null };
    return;
  }
  try {
    const has = (n) => (st.artifacts || []).some((a) => a.name === n);
    const [meta, components] = await Promise.all([
      has("discovery_meta.json") ? getJSON(artifactUrl(st.agent, "discovery_meta.json")) : null,
      has("components.json") ? getJSON(artifactUrl(st.agent, "components.json")) : [],
    ]);
    components.forEach((c) => { c.license = (c.licenses || []).join(", "); });
    state.discovery = { key, meta, components, error: null };
  } catch (err) {
    state.discovery = { key, meta: null, components: [], error: String(err) };
  }
  const t = state.table;
  const ecos = new Set(components().map((c) => c.ecosystem));
  if (t.ecosystem && !ecos.has(t.ecosystem)) t.ecosystem = "";
}

const components = () => state.discovery.components;

function discoveryPanel(st) {
  const { meta, error } = state.discovery;
  if (error) return h("div", { class: "error-box" }, h("strong", null, "Could not load discovery artifacts"), h("pre", null, error));
  return h("div", { class: "stack" },
    tilesRow(st.summary || {}, TILES),
    infoCard(meta),
    tableCard(),
    h("div", { class: "grid-2" },
      artifactsCard(st),
      h("div", { class: "placeholder" },
        h("strong", null, "Dependency graph"),
        h("span", null, "Coming in the next step."))),
  );
}

function infoCard(meta) {
  if (!meta) return h("div", { class: "card" }, h("p", { class: "muted" }, "discovery_meta.json not available."));
  const locks = Object.fromEntries((meta.npm_lockfiles || []).map((l) => [l.lockfile, l]));
  const failed = (meta.npm_lockfiles || []).filter((l) => l.status === "failed");

  const manifestRows = (meta.manifests || []).map((m) => {
    let tag;
    if (m.kind === "lockfile") {
      tag = m.origin === "generated"
        ? h("span", { class: "tag generated", title: (locks[m.path] || {}).command || "" }, "generated (--ignore-scripts)")
        : h("span", { class: "tag" }, "original");
    } else {
      tag = h("span", { class: "tag" }, "manifest");
    }
    return h("li", null, h("span", { class: "path" }, m.path), h("span", { class: "muted" }, m.ecosystem), tag);
  });
  failed.forEach((l) => manifestRows.push(h("li", null,
    h("span", { class: "path" }, l.manifest), h("span", { class: "muted" }, "npm"),
    h("span", { class: "tag failed", title: l.error || "" }, "lockfile generation failed"))));

  const tools = meta.tool_versions || {};
  const repo = meta.repo || {};
  return h("div", { class: "grid-2" },
    h("div", { class: "card" },
      h("h3", null, `Manifests and lockfiles (${(meta.manifests || []).length})`),
      h("ul", { class: "manifest-list" }, manifestRows),
      (meta.generated_lockfiles || []).length
        ? h("p", { class: "note" }, "Generated lockfiles were created with ",
            h("code", null, "npm install --package-lock-only --ignore-scripts"),
            ". No packages were installed and no install scripts ran.")
        : null),
    h("div", { class: "card" },
      h("h3", null, "Tool versions"),
      h("dl", { class: "kv" }, Object.entries(tools).map(([k, v]) => [h("dt", null, k), h("dd", null, v || "not found")])),
      h("h3", { style: "margin-top:20px" }, "Source"),
      h("dl", { class: "kv" },
        h("dt", null, "commit"), h("dd", { title: repo.commit_sha || "" }, (repo.commit_sha || "–").slice(0, 12)),
        h("dt", null, "committed"), h("dd", null, fmtDate(repo.commit_date) || "–"),
        h("dt", null, "ref"), h("dd", null, repo.ref || "default branch"))),
  );
}

function selectFilter(id, label, field, options) {
  const t = state.table;
  return h("label", { class: "app-select" }, h("span", { class: "label" }, label),
    h("select", { id, onchange: (e) => { t[field] = e.target.value; t.page = 1; renderTable(); } },
      options.map(([v, text]) => h("option", { value: v, selected: t[field] === v }, text))));
}

function tableCard() {
  const t = state.table;
  const ecos = [...new Set(components().map((c) => c.ecosystem || ""))].sort();
  let searchTimer;
  return h("div", { class: "card" },
    h("h3", null, "Components"),
    h("div", { class: "toolbar" },
      h("input", {
        type: "search", id: "comp-search", placeholder: "Search name, version, license or purl", value: t.q,
        "aria-label": "Search components",
        oninput: (e) => { clearTimeout(searchTimer); searchTimer = setTimeout(() => { t.q = e.target.value; t.page = 1; renderTable(); }, 120); },
      }),
      selectFilter("f-rel", "Type", "relationship",
        [["", "All"], ["direct", "Direct"], ["transitive", "Transitive"], ["unknown", "Unknown"]]),
      selectFilter("f-eco", "Ecosystem", "ecosystem",
        [["", "All"], ...ecos.map((e) => [e, e || "unknown"])]),
      selectFilter("f-scope", "Scope", "scope",
        [["", "All"], ["prod", "Prod"], ["dev", "Dev"], ["unknown", "Unknown"]]),
      h("span", { class: "count", id: "comp-count" })),
    h("div", { class: "table-wrap", id: "table-wrap" },
      h("table", null,
        h("thead", null, h("tr", { id: "comp-head" })),
        h("tbody", { id: "comp-body" }))),
    h("div", { class: "pager", id: "comp-pager" }));
}

function filteredComponents() {
  const t = state.table;
  const q = t.q.trim().toLowerCase();
  const match = (val, want) => !want || (want === "unknown" ? val == null : val === want);
  let rows = components().filter((c) =>
    match(c.relationship, t.relationship) &&
    match(c.scope, t.scope) &&
    (!t.ecosystem || c.ecosystem === t.ecosystem) &&
    (!q || [c.name, c.version, c.license, c.purl].some((v) => v && v.toLowerCase().includes(q))));
  const k = t.sortKey;
  const cmp = new Intl.Collator(undefined, { numeric: true, sensitivity: "base" }).compare;
  rows = rows.slice().sort((a, b) => {
    const av = a[k] ?? "", bv = b[k] ?? "";
    if (av === "" && bv !== "") return 1;   // empty values last in both directions
    if (bv === "" && av !== "") return -1;
    return cmp(String(av), String(bv)) * t.sortDir || cmp(a.name || "", b.name || "");
  });
  return rows;
}

function renderTable() {
  const body = $("comp-body");
  if (!body) return;
  const t = state.table;
  const rows = filteredComponents();
  const pages = Math.max(1, Math.ceil(rows.length / t.size));
  t.page = Math.min(Math.max(1, t.page), pages);
  const start = (t.page - 1) * t.size;
  const pageRows = rows.slice(start, start + t.size);

  $("comp-head").replaceChildren(...COLUMNS.map((col) => {
    const active = t.sortKey === col.key;
    return h("th", { scope: "col", "aria-sort": active ? (t.sortDir > 0 ? "ascending" : "descending") : null },
      h("button", { type: "button", onclick: () => {
        if (t.sortKey === col.key) t.sortDir *= -1; else { t.sortKey = col.key; t.sortDir = 1; }
        renderTable();
      } }, col.label, h("span", { class: "arrow", "aria-hidden": "true" }, active ? (t.sortDir > 0 ? "▲" : "▼") : "↕")));
  }));

  const dash = () => h("span", { class: "muted" }, "–");
  body.replaceChildren(...(pageRows.length ? pageRows.map((c) => h("tr", null,
    h("td", { class: "name" }, c.name || "–"),
    h("td", { class: "mono" }, c.version || "–"),
    h("td", null, c.ecosystem || dash()),
    h("td", null, c.scope ? h("span", { class: `pill ${c.scope}` }, c.scope) : dash()),
    h("td", null, c.relationship ? h("span", { class: `pill ${c.relationship}` }, c.relationship) : dash()),
    h("td", null, c.license || dash()),
    h("td", { class: "mono purl", title: c.purl || "" }, c.purl || "–"),
  )) : [h("tr", null, h("td", { colspan: COLUMNS.length, class: "muted" }, "No components match these filters."))]));

  const total = components().length;
  $("comp-count").textContent = rows.length === total
    ? `${fmtNum(total)} components` : `${fmtNum(rows.length)} of ${fmtNum(total)} components`;

  const go = (p) => () => { t.page = p; renderTable(); $("table-wrap").scrollTop = 0; };
  $("comp-pager").replaceChildren(
    h("span", { class: "info" }, rows.length
      ? `Showing ${fmtNum(start + 1)}–${fmtNum(start + pageRows.length)} of ${fmtNum(rows.length)}` : "No results"),
    h("label", { class: "app-select" }, h("span", { class: "label" }, "Rows"),
      h("select", { onchange: (e) => { t.size = Number(e.target.value); t.page = 1; renderTable(); } },
        PAGE_SIZES.map((n) => h("option", { value: n, selected: n === t.size }, n)))),
    h("button", { class: "btn", type: "button", disabled: t.page <= 1, onclick: go(1) }, "First"),
    h("button", { class: "btn", type: "button", disabled: t.page <= 1, onclick: go(t.page - 1) }, "Previous"),
    h("span", { class: "info", style: "margin:0 4px" }, `Page ${t.page} of ${pages}`),
    h("button", { class: "btn", type: "button", disabled: t.page >= pages, onclick: go(t.page + 1) }, "Next"),
    h("button", { class: "btn", type: "button", disabled: t.page >= pages, onclick: go(pages) }, "Last"),
  );
}

/* ---------- polling ---------- */

let polling = false;

async function refresh() {
  if (polling) return;
  polling = true;
  try {
    state.runs = await getJSON("/api/runs");
    const names = state.runs.map((r) => r.app_name);
    if (!names.includes(state.app)) state.app = names[0] || null;
    renderAppSelect();

    if (state.app) {
      const data = await getJSON(`/api/runs/${enc(state.app)}`);
      state.run = data.run;
      state.agents = data.agents || {};
      await loadDiscovery(statusForStage("discover"));
    } else {
      state.run = null;
      state.agents = {};
    }
    renderRunMeta();
    renderPipeline();
    renderPanel();
    $("poll-status").textContent = `Refreshing every 5 s · last checked ${new Date().toLocaleTimeString()}`;
  } catch (err) {
    $("poll-status").textContent = `Could not reach the API (${err.message}). Retrying…`;
  } finally {
    polling = false;
  }
}

function init() {
  const hash = readHash();
  if (hash.stage && STAGES.some((s) => s.id === hash.stage)) state.stage = hash.stage;
  state.app = hash.app;

  $("app-select").addEventListener("change", (e) => {
    state.app = e.target.value || null;
    state.discovery = { key: null, meta: null, components: [], error: null };
    state.table.page = 1;
    state.panelKey = null;
    writeHash();
    refresh();
  });

  refresh().then(writeHash);
  setInterval(refresh, POLL_MS);
}

init();
